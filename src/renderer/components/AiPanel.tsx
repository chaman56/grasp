import { useEffect, useState } from 'react'
import type { DiffLine, FnNode, Provider, SavedAnalysis } from '../../shared/types'
import { lens } from '../api'
import { SparkIcon } from '../icons'
import { explainPrompt } from '../prompt'
import { Markdown } from './Markdown'

interface Props {
  root: string
  node: FnNode
  lines: DiffLine[] | null
  callers: FnNode[]
  callees: FnNode[]
  saved: SavedAnalysis | undefined
  provider: Provider | null
  onSaved(nodeId: string, analysis: SavedAnalysis): void
  onOpenSettings(): void
}

export function AiPanel({ root, node, lines, callers, callees, saved, provider, onSaved, onOpenSettings }: Props) {
  const [streaming, setStreaming] = useState<string | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => lens.onExplainDelta((id, text) => id === node.id && setStreaming((s) => (s ?? '') + text)), [node.id])

  const run = async (): Promise<void> => {
    if (!lines) return
    setError(null)
    setStreaming('')
    const result = await lens.explain(root, node.id, node.hash, explainPrompt(node, lines, callers, callees))
    setStreaming(null)
    if (result.ok) onSaved(node.id, result.value)
    else if (result.error !== 'cancelled') setError(result.error)
  }

  if (!provider) {
    return (
      <div className="ai-empty">
        <p>Connect a local model (Ollama) or an OpenAI-compatible gateway to get a plain-language read of this code.</p>
        <button className="btn" onClick={onOpenSettings}>Add AI provider</button>
      </div>
    )
  }

  const current = saved && saved.hash === node.hash ? saved : undefined
  const text = streaming ?? current?.text
  return (
    <div className="ai">
      {streaming === '' && <p className="ai-waiting">Waiting for {provider.model}… reasoning models can take a minute before they answer.</p>}
      {text ? <Markdown text={text} /> : streaming === null && !error && <p className="muted">No analysis yet for this version of the code.</p>}
      {error && <div className="inline-error">{error}</div>}
      <div className="ai-foot">
        <span className="tag unverified" title="Generated by a model from the code text. Nothing was executed.">
          unverified · {streaming !== null ? provider.model : (current?.model ?? provider.model)}
        </span>
        {streaming !== null ? (
          <button className="btn ghost small" onClick={() => void lens.cancelExplain()}>Stop</button>
        ) : (
          <button className="btn small" onClick={() => void run()} disabled={!lines}>
            <SparkIcon /> {current ? 'Regenerate' : saved ? 'Analyze new version' : 'Analyze'}
          </button>
        )}
      </div>
    </div>
  )
}
